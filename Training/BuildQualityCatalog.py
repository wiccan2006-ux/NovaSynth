"""Reproducible multi-register curation and weighted/gated level proxy.
Not a listening panel, LUFS measurement, true-peak meter or uniqueness guarantee.
Keeps all original programs and Signature anchors; never rewrites saved states.
"""
from pathlib import Path
import numpy as np,json,math
root=Path(__file__).resolve().parents[1]
data=json.loads((root/'Training/QualityMeasurements.json').read_text());assert len(data)==812
f=np.array([x['features'] for x in data]);weights=np.array([.72/128]*128+[.25/24]*24+[.06/8]*8+[.08]);distance=np.empty((812,812))
for i in range(812):distance[i]=(np.abs(f-f[i])*weights).sum(axis=1)
selected=set(range(764,812))
for role in range(6):
 if not any(data[i]['role']==role for i in selected):selected.add(next(x['id'] for x in data if x['role']==role))
# Add genuinely distant measurements instead of filling a fixed count at any cost.
while len(selected)<192:
 candidates=[x['id'] for x in data if x['id'] not in selected]
 nearest={i:min(distance[i,j] for j in selected if data[j]['role']==data[i]['role']) for i in candidates}
 candidate=max(candidates,key=lambda i:nearest[i])
 if nearest[candidate]<.035:break
 selected.add(candidate)
rows=[];levels=[];peakLimited=0
for x in data:
 i=x['id'];anchors=[j for j in selected if data[j]['role']==x['role']];anchor=i if i in selected else min(anchors,key=lambda j:distance[i,j])
 # A shared weighted target; peak headroom takes priority over making every patch equally loud.
 target=.07
 gain=min(target/max(1e-8,x['weighted']),.07/max(1e-8,x['rms']),.70/max(1e-8,x['peak']))
 if gain<target/max(1e-8,x['weighted']):peakLimited+=1
 trim=max(-12,min(36,20*math.log10(gain)));rows.append((anchor,trim));levels.append(20*math.log10(max(1e-10,x['weighted']*10**(trim/20))))
out=['#pragma once','// Generated by Training/BuildQualityCatalog.py: 3 registers / weighted gated level / chord headroom.','namespace nova {','struct CatalogEntry {int representative;float trim;};','inline constexpr CatalogEntry catalog[812]={']
out.extend('{%d,%.4ff},'%row for row in rows);out+=['};',f'inline constexpr int curatedPresetCount={len(selected)};','}']
(root/'Source/CatalogData.h').write_text('\n'.join(out)+'\n')
report={'version':'0.19','presets':812,'representatives':len(selected),'variants':812-len(selected),'renders':812*8,'rate':22050,'gate':'max(1, attack+.6) seconds; .8s tail','conditions':'solo -12/0/+12 semitones at velocity .8; solo .35/.6; triads .8 and octave-up 1 (last condition repeats octave-up)','level':'38Hz highpass, +4dB high shelf at 1500Hz, 100ms blocks gated at -30dB relative energy. Proxy, not LUFS. Geometric mean of 3 registers; shared target .07; central stereo RMS cap .07; peak cap .70 across all tested conditions','curation':'normalized spectral/envelope/attack/width features averaged over 3 registers. Role-preserving farthest-point selection stops below .035 or at 192; 48 Signature anchors retained','peak_limited_presets':peakLimited,'gain_db_range':[min(t for _,t in rows),max(t for _,t in rows)],'weighted_db_range': [min(levels),max(levels)],'weighted_db_percentiles_10_50_90':np.percentile(levels,[10,50,90]).tolist(),'fl_studio_tested':False,'human_listening_completed':False}
(root/'Training/QualityReport.json').write_text(json.dumps(report,indent=2)+'\n');print(json.dumps(report,indent=2))
