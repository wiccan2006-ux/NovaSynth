"""Select representatives by measured distance; group other programs as variants.
No source program is removed or rewritten. Calibration is RMS, not LUFS.
"""
from pathlib import Path
import json, math
import numpy as np
root=Path(__file__).resolve().parents[1]
data=json.loads((root/'Training/CatalogMeasurements.json').read_text());assert len(data)==812
f=np.array([x['features'] for x in data]);weights=np.array([.72/128]*128+[.25/24]*24+[.06/8]*8+[.08]);distance=np.empty((812,812))
for i in range(812):distance[i]=(np.abs(f-f[i])*weights).sum(axis=1)
selected=set(range(764,812))
for role in range(6):
 if not any(data[i]['role']==role for i in selected):selected.add(next(x['id'] for x in data if x['role']==role))
while len(selected)<192:
 candidates=[x['id'] for x in data if x['id'] not in selected]
 selected.add(max(candidates,key=lambda i:min(distance[i,j] for j in selected if data[j]['role']==data[i]['role'])))
rows=[]
for x in data:
 i=x['id'];anchors=[j for j in selected if data[j]['role']==x['role']];anchor=i if i in selected else min(anchors,key=lambda j:distance[i,j])
 # Combined solo/chord energy; maximum 36 dB increase and measured chord peak <= .70.
 reference=math.sqrt((x['rms']**2+x['chord']**2)*.5)
 gain=min(.07/max(1e-8,reference),.70/max(1e-8,x['peak']))
 trim=max(-12,min(36,20*math.log10(gain)));rows.append((anchor,trim))
out=['#pragma once','// Generated by Training/BuildCatalog.py from reproducible stereo RMS/peak measurements.','namespace nova {','struct CatalogEntry {int representative;float trim;};','inline constexpr CatalogEntry catalog[812]={']
out.extend('{%d,%.4ff},'%row for row in rows);out+=['};','inline constexpr int curatedPresetCount=192;','}']
(root/'Source/CatalogData.h').write_text('\n'.join(out)+'\n')
report={'presets':812,'representatives':len(selected),'variants':812-len(selected),'conditions':'22050 Hz, gate max(1 s, attack+.6 s) + .8 s tail, solo velocity .8; major triad velocity .65; octave-up triad velocity 1 for peak cap; MIDI40 bass, 60 others','calibration':'combined stereo RMS target .07; measured peak cap .70; trim -12..36 dB; no LUFS/true peak claim','median_gain_db':float(np.median([t for _,t in rows])),'range_gain_db':[min(t for _,t in rows),max(t for _,t in rows)],'before_rms_db_range':[20*math.log10(min(x['rms'] for x in data)),20*math.log10(max(x['rms'] for x in data))],'after_rms_db_range':[20*math.log10(min(x['rms']*10**(rows[x['id']][1]/20) for x in data)),20*math.log10(max(x['rms']*10**(rows[x['id']][1]/20) for x in data))]}
(root/'Training/CatalogReport.json').write_text(json.dumps(report,indent=2)+'\n');print(json.dumps(report,indent=2))
