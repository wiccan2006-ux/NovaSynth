#!/usr/bin/env python3
"""Train the offline inverse-synth seed network. Requires numpy and scikit-learn.
Input: GenerateDataset.cpp raw float32 rows (155 features + 30 genes).
No recordings, downloaded model, network or third-party dataset is used.
"""
import os
os.environ.setdefault('OPENBLAS_NUM_THREADS','1')
os.environ.setdefault('OMP_NUM_THREADS','1')
import sys,json
from pathlib import Path
import numpy as np
from sklearn.neural_network import MLPRegressor
from sklearn.preprocessing import StandardScaler
from sklearn.metrics import mean_squared_error
root=Path(__file__).resolve().parents[1]
data=np.fromfile(sys.argv[1],dtype=np.float32).reshape(-1,185)
x,y=data[:,:155],data[:,155:]
# Fixed independent held-out partition; internal early-stopping uses training rows only.
train=np.arange(len(data))%6!=0
a=StandardScaler().fit(x[train]);xs=a.transform(x)
m=MLPRegressor(hidden_layer_sizes=(96,64),activation='relu',batch_size=128,max_iter=240,
    early_stopping=True,validation_fraction=.12,n_iter_no_change=18,random_state=340,
    learning_rate_init=.001,alpha=.005,verbose=False)
m.fit(xs[train],y[train]);pred=np.clip(m.predict(xs[~train]),0,1)
report={'model':'NovaSeed 1','architecture':[155,96,64,30],'training_source':'Procedural Nova Synth presets with randomized controls; no real instrument recordings',
 'rows':len(data),'training_rows':int(train.sum()),'held_out_rows':int((~train).sum()),'iterations':m.n_iter_,
 'held_out_parameter_mse':float(mean_squared_error(y[~train],pred)),
 'mean_parameter_baseline_mse':float(mean_squared_error(y[~train],np.tile(y[train].mean(axis=0),(int((~train).sum()),1)))),
 'limitations':'Parameter error is not perceptual audio accuracy. No actual instrument identification or measured real-instrument fidelity. Ambiguous inverse problem; predictions are seeds evaluated by audio search.'}
(root/'Training/ModelReport.json').write_text(json.dumps(report,indent=2)+'\n')
def arr(name,value):
 v=np.asarray(value).ravel();return f'inline constexpr float {name}[{len(v)}]={{\n'+',\n'.join(','.join(f'{float(t):.8e}f' for t in v[i:i+8]) for i in range(0,len(v),8))+'\n};\n'
s='#pragma once\n// Generated by Training/TrainModel.py. Original model weights, GPL-3.0-or-later.\nnamespace nova::neural_weights {\n'
s+=arr('mean',a.mean_)+arr('scale',a.scale_)
for i,(w,b) in enumerate(zip(m.coefs_,m.intercepts_)):s+=arr('w'+str(i),w.T)+arr('b'+str(i),b)
s+='}\n';(root/'Source/NeuralWeights.h').write_text(s)
# Saved held-out features/targets support native inference validation without training dependencies.
np.concatenate([x[~train][:64],y[~train][:64]],axis=1).astype(np.float32).tofile(root/'Training/Holdout.bin')
print(json.dumps(report,indent=2),flush=True)
